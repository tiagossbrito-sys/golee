import { createRequire } from 'node:module'
const require = createRequire(import.meta.url)
const { chromium, devices } = require(process.env.PLAYWRIGHT_PATH ?? 'playwright')
const out = process.env.OUT ?? '/tmp/claude-0/shots'
const browser = await chromium.launch()
const ctx = await browser.newContext({ ...devices['Pixel 7'], locale: 'pt-BR', timezoneId: 'America/Sao_Paulo', colorScheme: 'light' })
const page = await ctx.newPage()
const errors = []
page.on('pageerror', (e) => errors.push(String(e)))
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()) })
await page.goto('http://localhost:4173/')
await page.waitForSelector('text=Qual seu gole hoje?')
await page.screenshot({ path: `${out}/01-onb1.png` })
await page.fill('input[placeholder="Seu nome"]', 'Tiago')
await page.click('text=Masculino')
await page.click('text=Continuar')
await page.waitForSelector('text=Seu ritmo')
await page.screenshot({ path: `${out}/02-onb2.png` })
await page.click('text=Continuar')
await page.waitForSelector('text=Com quem você joga?')

await page.screenshot({ path: `${out}/03-onb3.png` })
await page.click('button.btn:text-is("Começar")')
await page.waitForSelector('button.gole-btn')
await page.screenshot({ path: `${out}/04-hoje.png`, fullPage: true })
for (let i = 0; i < 4; i++) { await page.click('button.gole-btn'); await page.waitForTimeout(150); const ov = await page.$('.overlay'); if (ov) { await page.screenshot({ path: `${out}/05-super.png` }); await page.click('text=Continuar') } }
await page.screenshot({ path: `${out}/06-hoje-4goles.png` })
await page.click('text=Grupo')
await page.waitForSelector('text=Gole do Grupo')
await page.screenshot({ path: `${out}/07-grupo.png`, fullPage: true })
await page.click('text=Semana')
await page.screenshot({ path: `${out}/08-grupo-semana.png` })
await page.click('text=Coleção')
await page.waitForSelector('text=Personagens')
await page.screenshot({ path: `${out}/09-colecao.png`, fullPage: true })
await page.click('text=Eu')
await page.waitForSelector('text=Meta e copo')
await page.screenshot({ path: `${out}/10-eu.png`, fullPage: true })
// persistência: recarregar mantém estado
await page.reload()
await page.waitForSelector('button.gole-btn')
const total = await page.textContent('.hoje-head .total')
console.log('total após reload:', total)
const manifest = await page.evaluate(async () => { const r = await fetch('/manifest.webmanifest'); return (await r.json()).name })
console.log('manifest:', manifest)
const sw = await page.evaluate(async () => !!(await navigator.serviceWorker.getRegistration()))
console.log('service worker registrado:', sw)
console.log('erros:', errors.length ? errors : 'nenhum')
await browser.close()
